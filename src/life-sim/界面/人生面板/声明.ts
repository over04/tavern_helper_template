/**
 * 把待发送状态拼成随消息附上的中文标签声明。
 *
 * 这里只用于界面上「待发送命令」的原文显示，真正随消息发出的是 脚本/发送拦截.txt 拼的那一份。
 * 两处的规则必须一致，改动须同步。
 */

import type { 待发送 } from './待发送';

export const 拼声明 = (状态: 待发送, 模式: string): string => {
  const 段: string[] = [];

  // 开局声明整段由界面拼好，这里原样放在最前
  const 开局 = String(状态.开局 || '').trim();
  if (开局) {
    段.push(开局);
  }

  for (const 项 of 状态.选择) {
    const 事件 = String(项.事件 || '').trim();
    const 选项 = String(项.选项 || '').trim();
    if (!事件 || !选项) {
      continue;
    }
    const 命运点 = String(项.命运点 || '').trim();
    const 配点 = 命运点 ? ` 命运点="${命运点}"` : '';
    if (选项 === '其他') {
      段.push(`<选择 事件="${事件}" 选项="其他"${配点}>${String(项.行动原文 || '').trim()}</选择>`);
    } else {
      段.push(`<选择 事件="${事件}" 选项="${选项}"${配点}/>`);
    }
  }

  for (const 方向 of 状态.心向) {
    const 文本 = String(方向 || '').trim();
    if (文本) {
      段.push(`<心向>${文本}</心向>`);
    }
  }

  // 模式切换只在当前模式与基准模式不同时附一次；切走又切回时两者相同，不附
  if (状态.模式基准 && 状态.模式基准 !== 模式) {
    段.push(`<模式切换>${模式}</模式切换>`);
  }

  return 段.join('\n');
};
