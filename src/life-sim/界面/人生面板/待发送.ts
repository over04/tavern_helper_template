/**
 * 界面内已选、尚未随消息发出的内容。存聊天变量，界面被重建后仍能读回。
 *
 * 每次操作前重读一次聊天变量，避免界面的内存副本与它不一致。
 *
 * 存聊天变量而不是全局变量：全局变量跨聊天共用，换到别的角色卡或同一张卡的另一个聊天时，
 * 上一次留下的模式基准会被当成这一轮的基准，多出一条 <模式切换> 声明。
 */

import { 写输入框 } from './发送';

export type 待发送选择 = {
  事件: string;
  /** 选项序号 '1'~'4'；手写行动为 '其他' */
  选项: string;
  /** 手写行动的原文，选项为序号时为空 */
  行动原文: string;
  /** '' | '重掷' | '加值' | '改判' */
  命运点: string;
};

export type 待发送 = {
  选择: 待发送选择[];
  心向: string[];
  /** 开局声明，尚未开局时为空串 */
  开局: string;
  /** 模式基准：上一次发送之后的模式，用来判断本回合要不要附模式切换声明 */
  模式基准: string;
};

export const 空待发送 = (模式基准 = ''): 待发送 => ({ 选择: [], 心向: [], 开局: '', 模式基准 });

const 聊天表 = (): Record<string, any> => {
  try {
    return getVariables({ type: 'chat' }) || {};
  } catch (error) {
    console.error('人生面板：读取聊天变量失败', error);
    return {};
  }
};

export const 读待发送 = (): 待发送 => {
  const 存 = 聊天表().待发送;
  const 状态 = 存 && typeof 存 === 'object' ? 存 : {};
  return {
    选择: Array.isArray(状态.选择) ? 状态.选择 : [],
    心向: Array.isArray(状态.心向) ? 状态.心向 : [],
    开局: typeof 状态.开局 === 'string' ? 状态.开局 : '',
    模式基准: String(状态.模式基准 || ''),
  };
};

export const 写待发送 = (状态: 待发送) => {
  const 聊天 = 聊天表();
  _.set(聊天, ['待发送'], { ...状态 });
  try {
    replaceVariables(聊天, { type: 'chat' });
  } catch (error) {
    console.error('人生面板：写入待发送状态失败', error);
  }
};

/** 待发送状态变更后的广播事件名：改动待发送状态的组件派发它，显示待发送状态的组件监听它 */
export const 待发送更新事件 = 'ls:待发送更新';

/** 当前楼层变量里的模式；读取不到时按月推进处理 */
export const 当前模式 = (): string => {
  const 数据 = Mvu.getMvuData({ type: 'message', message_id: 'latest' });
  const stat = 数据 && 数据.stat_data;
  return String((stat && stat.时间 && stat.时间.模式) || '月推进');
};

/**
 * 把待发送状态拼成随消息发出的中文标签声明；没有内容时返回空串。
 *
 * 拼装只有这一处实现。
 */
export const 拼声明 = (状态: 待发送): string => {
  const 段: string[] = [];

  // 开局声明整段由界面拼好，原样放在最前
  const 开局 = String(状态.开局 || '').trim();
  if (开局) {
    段.push(开局);
  }

  for (const 项 of 状态.选择) {
    const 事件 = String(项?.事件 || '').trim();
    const 选项 = String(项?.选项 || '').trim();
    if (!事件 || !选项) {
      continue;
    }
    const 命运点 = String(项.命运点 || '').trim();
    const 配点 = 命运点 ? ` 命运点="${命运点}"` : '';
    if (选项 === '其他') {
      段.push(`<选择 事件="${事件}" 选项="其他"${配点}>${String(项.行动原文 || '').trim()}</选择>`);
    } else {
      段.push(`<选择 事件="${事件}" 选项="${选项}"${配点}/>`);
    }
  }

  for (const 方向 of 状态.心向) {
    const 文本 = String(方向 || '').trim();
    if (文本) {
      段.push(`<心向>${文本}</心向>`);
    }
  }

  // 模式切换只在当前模式与基准模式不同时附一次；切走又切回时两者相同，不附
  const 模式 = 当前模式();
  if (状态.模式基准 && 状态.模式基准 !== 模式) {
    段.push(`<模式切换>${模式}</模式切换>`);
  }

  return 段.join('\n');
};

/**
 * 待发送状态：模块级单例。
 *
 * 界面内所有组件共享同一份，任一处改动其余各处立刻跟着变；
 * 每次调用 use待发送() 返回的都是同一批操作入口。
 */
const 状态 = ref<待发送>(读待发送());

/** 待发送状态的响应式副本与操作入口 */
export const use待发送 = () => {
  const 刷新 = () => {
    状态.value = 读待发送();
  };

  const 提交 = (下一个: 待发送) => {
    状态.value = 下一个;
    写待发送(下一个);
    // 声明立刻写进酒馆输入框：玩家点一下就能看见要发出去的内容。
    // 全屏时界面随后代按发送键；紧凑面板里玩家看得见输入框，自己按
    写输入框(拼声明(下一个));
  };

  /** 记一条选择：同一事件只留一条，改选另一条时替换掉上一次的记录 */
  const 选选项 = (事件: string, 选项: string, 行动原文 = '') => {
    const 当前 = 读待发送();
    const 旧的 = 当前.选择.find(项 => 项.事件 === 事件);
    const 其余 = 当前.选择.filter(项 => 项.事件 !== 事件);
    提交({
      ...当前,
      选择: [...其余, { 事件, 选项, 行动原文, 命运点: 旧的 ? String(旧的.命运点 || '') : '' }],
    });
  };

  /** 记一条命运点声明：同一事件只留一条，未点选过选项时忽略 */
  const 设命运点 = (事件: string, 命运点: string) => {
    const 当前 = 读待发送();
    if (!当前.选择.some(项 => 项.事件 === 事件)) {
      return;
    }
    提交({
      ...当前,
      选择: 当前.选择.map(项 => (项.事件 === 事件 ? { ...项, 命运点 } : 项)),
    });
  };

  const 移除选择 = (事件: string) => {
    const 当前 = 读待发送();
    提交({ ...当前, 选择: 当前.选择.filter(项 => 项.事件 !== 事件) });
  };

  const 增心向 = (方向: string) => {
    const 文本 = String(方向 || '').trim();
    if (!文本) {
      return;
    }
    const 当前 = 读待发送();
    if (当前.心向.includes(文本)) {
      return;
    }
    提交({ ...当前, 心向: [...当前.心向, 文本] });
  };

  const 移除心向 = (方向: string) => {
    const 当前 = 读待发送();
    提交({ ...当前, 心向: 当前.心向.filter(项 => 项 !== 方向) });
  };

  /** 记一条开局声明：开局只发生一次，写新的即替换旧的 */
  const 设开局 = (声明: string) => {
    const 当前 = 读待发送();
    提交({ ...当前, 开局: String(声明 || '').trim() });
  };

  /** 模式切换时整体作废：已选的事件选项、命运点与心向都不再随消息发出 */
  const 清空 = () => {
    提交(空待发送(当前模式()));
  };

  return { 状态, 刷新, 选选项, 设命运点, 移除选择, 增心向, 移除心向, 设开局, 清空 };
};
