/**
 * 界面内已选、尚未随消息发出的内容。存聊天变量，界面被重建后仍能读回。
 *
 * 每次操作前重读一次聊天变量，避免界面的内存副本与它不一致。
 *
 * 存聊天变量而不是全局变量：全局变量跨聊天共用，换到别的角色卡或同一张卡的另一个聊天时，
 * 上一次留下的模式基准会被当成这一轮的基准，多出一条 <模式切换> 声明。
 */

import { 写输入框 } from './发送';
import { useDataStore } from './store';

export type 待发送选择 = {
  事件: string;
  /** 选项序号 '1'~'4'；手写行动为 '其他' */
  选项: string;
  /** 手写行动的原文，选项为序号时为空 */
  行动原文: string;
  /** '' | '重掷' | '加值' | '改判' */
  命运点: string;
};

export type 待发送 = {
  选择: 待发送选择[];
  心向: string[];
  /** 开局声明，尚未开局时为空串 */
  开局: string;
  /** 模式基准：上一次发送之后的模式，用来判断本回合要不要附模式切换声明 */
  模式基准: string;
};

export const 空待发送 = (模式基准 = ''): 待发送 => ({ 选择: [], 心向: [], 开局: '', 模式基准 });

/* ── 转义 ──
   事件名与选项由模型生成，行动原文与心向由玩家自由输入，都可能含引号、尖括号与 &。
   直接拼进 XML 会让判定骰脚本的正则解析错位或提前截断，所以按 XML 规则转义。 */

/** 属性值：转义 & 与双引号，尖括号一并转义以免歧义 */
const 转义属性 = (值: string): string =>
  值.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** 元素内容：转义 & 与尖括号 */
const 转义文本 = (值: string): string =>
  值.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const 聊天表 = (): Record<string, any> => {
  try {
    return getVariables({ type: 'chat' }) || {};
  } catch (error) {
    console.error('人生面板：读取聊天变量失败', error);
    return {};
  }
};

export const 读待发送 = (): 待发送 => {
  const 存 = 聊天表().待发送;
  const 状态 = 存 && typeof 存 === 'object' ? 存 : {};
  return {
    选择: Array.isArray(状态.选择) ? 状态.选择 : [],
    心向: Array.isArray(状态.心向) ? 状态.心向 : [],
    开局: typeof 状态.开局 === 'string' ? 状态.开局 : '',
    模式基准: String(状态.模式基准 || ''),
  };
};

export const 写待发送 = (状态: 待发送) => {
  const 聊天 = 聊天表();
  _.set(聊天, ['待发送'], { ...状态 });
  try {
    replaceVariables(聊天, { type: 'chat' });
  } catch (error) {
    console.error('人生面板：写入待发送状态失败', error);
  }
};

/** 待发送状态变更后的广播事件名：改动待发送状态的组件派发它，显示待发送状态的组件监听它 */
export const 待发送更新事件 = 'ls:待发送更新';

/**
 * 当前楼层变量里的模式；读取不到时按月推进处理。
 *
 * 先读界面内的响应式数据：改 store.data 之后，MVU 的写回要等 watch 的微任务，
 * 此刻同步读 Mvu.getMvuData 拿到的还是旧值。模式切换就是「改完变量立刻读」，
 * 走 MVU 那条路会读到切换前的模式、与刚写入的基准相同，这一条模式切换就附不上。
 */
export const 当前模式 = (): string => {
  try {
    const 值 = useDataStore().data?.时间?.模式;
    if (值) {
      return String(值);
    }
  } catch {
    // store 尚未就绪时退回读 MVU 变量
  }
  const 数据 = Mvu.getMvuData({ type: 'message', message_id: 'latest' });
  const stat = 数据 && 数据.stat_data;
  return String((stat && stat.时间 && stat.时间.模式) || '月推进');
};

/** 模式切换声明用的标签名 */
const 模式切换标签 = '模式切换';

/** 从拼好的声明里取出模式切换后的新模式；没有这一条时返回空串 */
export const 取模式切换 = (声明: string): string => {
  const 命中 = String(声明 || '').match(new RegExp(`<${模式切换标签}>(.*?)</${模式切换标签}>`));
  return 命中 ? 命中[1] : '';
};

/**
 * 把待发送状态拼成随消息发出的中文标签声明；没有内容时返回空串。
 *
 * 拼装只有这一处实现。
 */
export const 拼声明 = (状态: 待发送): string => {
  const 段: string[] = [];

  // 开局声明整段由界面拼好，原样放在最前
  const 开局 = String(状态.开局 || '').trim();
  if (开局) {
    段.push(开局);
  }

  for (const 项 of 状态.选择) {
    const 事件 = String(项?.事件 || '').trim();
    const 选项 = String(项?.选项 || '').trim();
    if (!事件 || !选项) {
      continue;
    }
    const 命运点 = String(项?.命运点 || '').trim();
    const 配点 = 命运点 ? ` 命运点="${转义属性(命运点)}"` : '';
    if (选项 === '其他') {
      const 行动 = String(项?.行动原文 || '').trim();
      // 手写行动没有原文时整条不附：附上去会开出一条无内容的判定
      if (行动) {
        段.push(`<选择 事件="${转义属性(事件)}" 选项="其他"${配点}>${转义文本(行动)}</选择>`);
      }
    } else {
      段.push(`<选择 事件="${转义属性(事件)}" 选项="${转义属性(选项)}"${配点}/>`);
    }
  }

  for (const 方向 of 状态.心向) {
    const 文本 = String(方向 || '').trim();
    if (文本) {
      段.push(`<心向>${转义文本(文本)}</心向>`);
    }
  }

  // 模式切换只在当前模式与基准模式不同时附一次；切走又切回时两者相同，不附
  const 模式 = 当前模式();
  if (状态.模式基准 && 状态.模式基准 !== 模式) {
    段.push(`<${模式切换标签}>${转义文本(模式)}</${模式切换标签}>`);
  }

  return 段.join('\n');
};

/**
 * 待发送状态：模块级单例。
 *
 * 界面内所有组件共享同一份，任一处改动其余各处立刻跟着变；
 * 每次调用 use待发送() 返回的都是同一批操作入口。
 */
const 状态 = ref<待发送>(读待发送());

/** 待发送状态的响应式副本与操作入口 */
export const use待发送 = () => {
  const 刷新 = () => {
    状态.value = 读待发送();
  };

  const 提交 = (下一个: 待发送) => {
    状态.value = 下一个;
    写待发送(下一个);
    // 声明立刻写进酒馆输入框：玩家点一下就能看见要发出去的内容。
    // 全屏时界面随后代替玩家按下发送键；紧凑面板里玩家能看见输入框，自行按下
    写输入框(拼声明(下一个));
  };

  /**
   * 记一条选择：直接接在末尾。
   *
   * 不做去重，也不做「再点一次即取消」：那类判断要在界面与状态两处各维护一份，
   * 稍有不同步就会重复写入。玩家点了就加一条，加错了自己删。
   */
  const 选选项 = (事件: string, 选项: string, 行动原文 = '', 命运点 = '') => {
    const 当前 = 读待发送();
    提交({
      ...当前,
      选择: [...当前.选择, { 事件, 选项, 行动原文, 命运点 }],
    });
  };

  const 移除选择 = (事件: string) => {
    const 当前 = 读待发送();
    提交({ ...当前, 选择: 当前.选择.filter(项 => 项?.事件 !== 事件) });
  };

  const 增心向 = (方向: string) => {
    const 文本 = String(方向 || '').trim();
    if (!文本) {
      return;
    }
    const 当前 = 读待发送();
    if (当前.心向.includes(文本)) {
      return;
    }
    提交({ ...当前, 心向: [...当前.心向, 文本] });
  };

  const 移除心向 = (方向: string) => {
    const 当前 = 读待发送();
    提交({ ...当前, 心向: 当前.心向.filter(项 => 项 !== 方向) });
  };

  /** 记一条开局声明：开局只发生一次，写新的即替换旧的 */
  const 设开局 = (声明: string) => {
    const 当前 = 读待发送();
    提交({ ...当前, 开局: String(声明 || '').trim() });
  };

  /**
   * 模式切换时整体作废：已选的事件选项、命运点与心向都不再随消息发出。
   *
   * 基准由调用方传入切换前的模式。必须先改 `时间.模式` 再调它，否则拼声明时
   * 读到的仍是旧模式、与刚写入的基准相同，这一条模式切换就附不上。
   */
  const 清空 = (模式基准?: string) => {
    提交(空待发送(模式基准 ?? 当前模式()));
  };

  /**
   * 发送成功后清空，并把模式基准记成这次真正告知过的新模式。
   *
   * 基准不能在这里读 `当前模式()`：这一刻 `latest` 已经是刚创建的玩家消息楼层，
   * 它的 stat_data 是空的，读出来只会回落成默认的月推进。
   */
  const 发送后清空 = () => {
    const 当前 = 读待发送();
    const 新模式 = 取模式切换(拼声明(当前));
    提交(空待发送(新模式 || 当前.模式基准));
  };

  return { 状态, 刷新, 选选项, 移除选择, 增心向, 移除心向, 设开局, 清空, 发送后清空 };
};
